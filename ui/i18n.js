window.LANG = "fi";
window.t = (key, vars = {}) => {
  let s = (window.I18N[window.LANG] || {})[key] ?? window.I18N.fi[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  return s;
};
window.applyI18n = (root = document) => {
  root.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t(el.dataset.t); });
  root.querySelectorAll("[data-th]").forEach((el) => { el.innerHTML = t(el.dataset.th); });
  root.querySelectorAll("[data-tt]").forEach((el) => { el.title = t(el.dataset.tt); });
  root.querySelectorAll("[data-tp]").forEach((el) => { el.placeholder = t(el.dataset.tp); });
};
window.setLang = (lang) => {
  const l = lang === "en" ? "en" : "fi";
  if (l === window.LANG && document.documentElement.lang === l) return false;
  window.LANG = l;
  document.documentElement.lang = l;
  window.applyI18n();
  return true;
};
